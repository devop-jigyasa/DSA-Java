package JavaBasics;

public class IncrementDecrement {
    public static void amin(String[] args){

        int x = 10;
        System.out.println(x++);
        System.out.println(x);
  
        int xx = 10;
        System.out.println(++xx);
        System.out.println(xx);

        int xxx = 10;
        System.out.println(--xxx);
        System.out.println(xxx);

        int xxxx = 10;
        System.out.println(xxxx--);
        System.out.println(xxxx);

        int xs = 10;
        int y = xs++;
        System.out.println(xs+" "+y);
    }
}
