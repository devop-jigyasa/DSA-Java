package JavaBasics;
public class Typecasting {
    public static void main(String[] args){

// Type Casting (Data type Conversion)

        char ch = '4';
        int x = ch;
        System.out.print(x);

        char chh = '4';
        int xx = (int)chh;
        System.out.print(xx);

        char chhh = '%';
        System.out.print((int)chhh);

        int xxx = 126;
        System.out.print((char)xxx);
    }
}
